// Regenerates public/js/map-coords.js: exact map pins for every restaurant
// location in the menu data that matches a Disneyland Resort dining location
// on ThemeParks.wiki. Run after adding new restaurants:
//
//   node scripts/build-map-coords.js
//
// Locations that don't match keep working: the app falls back to a maps search.
const fs = require('node:fs');
const path = require('node:path');

const RESORT_ID = 'bfc89fd6-314d-44b4-b89e-df1a89cf991e';
const INDEX = path.join(__dirname, '..', 'public', 'index.html');
const OUT = path.join(__dirname, '..', 'public', 'js', 'map-coords.js');

// Every pin must land inside the resort, so a bad name match can't send
// someone across town.
const inResort = ([lat, lng]) => lat > 33.800 && lat < 33.818 && lng > -117.930 && lng < -117.910;
const norm = (s) => s.toLowerCase().replace(/&/g, 'and').replace(/[^a-z0-9]/g, '');

function bestMatch(loc, restaurants) {
  // "Napa Rose — Grand Californian Hotel / Pool Bar" -> "naparose"
  const n = norm(loc.split(' / ')[0].split(' — ')[0]);
  if (n.length < 4) return null;
  const exact = restaurants.find(r => norm(r.name) === n);
  if (exact) return exact;
  const prefix = restaurants
    .filter(r => n.length > 5 && (norm(r.name).startsWith(n) || n.startsWith(norm(r.name))))
    .sort((a, b) => a.name.length - b.name.length);
  return prefix[0] || null;
}

async function main() {
  const html = fs.readFileSync(INDEX, 'utf8');
  const locs = [...new Set([...html.matchAll(/\bloc: "([^"]+)"/g)].map(m => m[1]))].sort();

  const res = await fetch('https://api.themeparks.wiki/v1/entity/' + RESORT_ID + '/children');
  if (!res.ok) throw new Error('ThemeParks.wiki request failed: ' + res.status);
  const restaurants = (await res.json()).children
    .filter(c => c.entityType === 'RESTAURANT' && c.location && c.location.latitude);

  const coords = {};
  const unmatched = [];
  for (const loc of locs) {
    const r = bestMatch(loc, restaurants);
    const pin = r && [+r.location.latitude.toFixed(6), +r.location.longitude.toFixed(6)];
    if (pin && inResort(pin)) {
      coords[loc] = pin;
      console.log('pin     ' + loc + '  ->  ' + r.name);
    } else {
      unmatched.push(loc);
    }
  }
  unmatched.forEach(loc => console.log('search  ' + loc));

  const body = Object.entries(coords)
    .map(([loc, [lat, lng]]) => '    ' + JSON.stringify(loc) + ': [' + lat + ', ' + lng + '],')
    .join('\n');
  fs.writeFileSync(OUT,
    '// GENERATED by scripts/build-map-coords.js from ThemeParks.wiki. Do not edit by hand.\n' +
    '// Restaurant location (exactly as written in the menu data) -> [latitude, longitude].\n' +
    '(function(root) {\n' +
    '  const MAP_COORDS = {\n' + body + '\n  };\n' +
    "  if (typeof module !== 'undefined' && module.exports) module.exports = MAP_COORDS;\n" +
    '  else root.MAP_COORDS = MAP_COORDS;\n' +
    '})(this);\n');
  console.log('\n' + Object.keys(coords).length + ' exact pins, ' + unmatched.length + ' search fallbacks -> ' + path.relative(process.cwd(), OUT));
}

main().catch(err => { console.error(err); process.exit(1); });
